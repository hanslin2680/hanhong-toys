var HH_RTL = { ar: true };

function hhResolve(dict, path) {
  return path.split(".").reduce(function (o, k) { return o ? o[k] : undefined; }, dict);
}

function hhApply(page) {
  var select = document.getElementById("langSelect");
  var saved = null;
  try { saved = localStorage.getItem("hh_lang"); } catch (e) {}
  if (saved && HH_I18N[saved] && select) select.value = saved;

  function apply(lang) {
    var dict = HH_I18N[lang] || HH_I18N.en;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = hhResolve(dict, el.getAttribute("data-i18n"));
      if (v !== undefined) el.textContent = v;
    });
    document.documentElement.lang = lang;
    document.documentElement.dir = HH_RTL[lang] ? "rtl" : "ltr";
    if (page !== "home" && dict.series[page]) {
      document.title = dict.series[page].t + " | HANHONG PLASTIC TOYS FACTORY";
    }
    try { localStorage.setItem("hh_lang", lang); } catch (e) {}
  }

  apply(select ? select.value : "en");
  if (select) select.addEventListener("change", function () { apply(select.value); });
}
